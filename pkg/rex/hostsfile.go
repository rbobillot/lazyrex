const (
	// HostsFileName is the file lazyrex owns in Rex's config directory.
	HostsFileName = "lazyrex-hosts.lua"
	// HostsFileMarker is the first line of every file lazyrex writes; a file
	// with any other first line is not lazyrex's.
	HostsFileMarker = "-- lazyrex-hosts v1: generated by lazyrex, which replaces this whole file. Do not edit it."
	hostsFileNote   = "-- Each host reaches the stable socket of a forward-mode SSH target while lazyrex runs with it active."
	hostLabelSuffix = "-lazyrex"
	// maxHostLabel keeps the label one segment of the binary's label regex,
	// whose segments hold at most 63 characters.
	maxHostLabel = 63
	maxLabelSlug = maxHostLabel - len(hostLabelSuffix)
)

var (
	hostLabelRE  = regexp.MustCompile(`^[a-z0-9-]+-lazyrex$`)
	declaredRE   = regexp.MustCompile(`^.+\.lua:\d+$`)
	stableSockRE = regexp.MustCompile(`^gui-[a-z0-9.-]*_[0-9a-f]{16}\.sock$`)
)

// HostEntry is the host lazyrex declares for a target.
type HostEntry struct{ Target, Label, Endpoint string }

// SkippedHost is a target lazyrex declares no host for, and why.
type SkippedHost struct{ Target, Why string }

// StableSocketPath is the stable socket of an SSH target in the runtime
// directory dir.
func StableSocketPath(dir, name string, spec SSHSpec) string {
	return dir + "/" + stableSocketName(name, spec)
}

// HostLabel is the label of the host lazyrex declares for the target name:
// its letters and digits lowercased, every other run one '-', then -lazyrex.
func HostLabel(name string) (string, error) {
	var b strings.Builder
	for _, r := range strings.ToLower(name) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case !strings.HasSuffix(b.String(), "-"):
			b.WriteByte('-')
		}
	}
	s := strings.Trim(b.String(), "-")
	s = strings.TrimRight(s[:min(len(s), maxLabelSlug)], "-")
	if s == "" {
		return "", errors.New("it needs letters or digits")
	}
	return s + hostLabelSuffix, nil
}

// HostsFileEntries are the hosts of every forward-mode SSH target of the
// config, sorted by label, and the targets left out: no label, a label
// another target shares, or a socket path Rex cannot reach.
func HostsFileEntries(dir string, ts []Target) ([]HostEntry, []SkippedHost) {
	var es []HostEntry
	var skipped []SkippedHost
	byLabel := map[string][]string{}
	for _, t := range ts {
		if t.Kind != TargetSSH || t.Source != SourceConfig || !t.SSH.forward() {
			continue
		}
		label, err := HostLabel(t.Name)
		if err != nil {
			skipped = append(skipped, SkippedHost{t.Name, fmt.Sprintf("%q gives no Rex host label (%v); rename the target.", t.Name, err)})
			continue
		}
		uri := SocketURI(StableSocketPath(dir, t.Name, t.SSH))
		if _, err := NormalizeEndpoint(uri); err != nil {
			skipped = append(skipped, SkippedHost{t.Name, fmt.Sprintf("the socket of %q cannot be declared: %v.", t.Name, err)})
			continue
		}
		byLabel[label] = append(byLabel[label], t.Name)
		es = append(es, HostEntry{Target: t.Name, Label: label, Endpoint: uri})
	}
	es = slices.DeleteFunc(es, func(e HostEntry) bool {
		names := byLabel[e.Label]
		if len(names) < 2 {
			return false
		}
		other := names[0]
		if other == e.Target {
			other = names[1]
		}
		skipped = append(skipped, SkippedHost{e.Target, fmt.Sprintf("targets %q and %q would share the label %s; rename one.", e.Target, other, e.Label)})
		return true
	})
	slices.SortFunc(es, func(a, b HostEntry) int { return strings.Compare(a.Label, b.Label) })
	return es, skipped
}

// LuaString is s as one double-quoted Lua literal. Every byte outside
// printable ASCII is a 3-digit decimal escape, the same in Lua 5.1, LuaJIT
// and 5.4, and never extended by a digit after it.
func LuaString(s string) (string, error) {
	switch {
	case !utf8.ValidString(s):
		return "", errors.New("not valid UTF-8")
	case strings.IndexByte(s, 0) >= 0:
		return "", errors.New("contains a NUL byte")
	}
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 0x20 && c <= 0x7e:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03d", c)
		}
	}
	b.WriteByte('"')
	return b.String(), nil
}

// HostLine is the rex.host declaration of e; it refuses a label or endpoint
// lazyrex would never declare.
func HostLine(e HostEntry) (string, error) {
	if len(e.Label) > maxHostLabel || !hostLabelRE.MatchString(e.Label) {
		return "", fmt.Errorf("label %q is not one lazyrex declares", e.Label)
	}
	if _, err := NormalizeEndpoint(e.Endpoint); err != nil {
		return "", err
	}
	label, err := LuaString(e.Label)
	if err != nil {
		return "", err
	}
	endpoint, err := LuaString(e.Endpoint)
	if err != nil {
		return "", err
	}
	return "rex.host({ label = " + label + ", endpoint = " + endpoint + " })", nil
}

// RenderHostsFile is the whole file declaring es, sorted by label, so two
// lazyrex with the same targets write the same bytes.
func RenderHostsFile(es []HostEntry) ([]byte, error) {
	es = slices.Clone(es)
	slices.SortFunc(es, func(a, b HostEntry) int { return strings.Compare(a.Label, b.Label) })
	var b bytes.Buffer
	b.WriteString(HostsFileMarker + "\n" + hostsFileNote + "\n\n")
	for _, e := range es {
		line, err := HostLine(e)
		if err != nil {
			return nil, err
		}
		b.WriteString(line + "\n")
	}
	return b.Bytes(), nil
}

// IncludeLine is the line init.lua needs to run the file at path; lazyrex
// only shows it. loadfile returns nil for a missing or broken file.
func IncludeLine(path string) (string, error) {
	lit, err := LuaString(path)
	if err != nil {
		return "", err
	}
	return "do local f = loadfile(" + lit + "); if f then f() end end", nil
}

// ConfigDiagnostic is one complaint of rex config check or reload.
type ConfigDiagnostic struct {
	Severity string `json:"severity"`
	Source   string `json:"source"`
	Message  string `json:"message"`
}

// Text is the diagnostic as one line: SOURCE: MESSAGE.
func (d ConfigDiagnostic) Text() string {
	if d.Source == "" {
		return d.Message
	}
	return d.Source + ": " + d.Message
}

// ConfigCheckOutput is `rex config check --json`. Exists and Diagnostics
// are nil when the output leaves them out.
type ConfigCheckOutput struct {
	Path        string              `json:"path"`
	Exists      *bool               `json:"exists"`
	Diagnostics *[]ConfigDiagnostic `json:"diagnostics"`
}

// ConfigReloadOutput is `rex config reload --json`.
type ConfigReloadOutput struct {
	Generation  Loose              `json:"generation"`
	Diagnostics []ConfigDiagnostic `json:"diagnostics"`
}

func parseObject(b []byte, v any) error {
	if t := bytes.TrimSpace(b); len(t) == 0 || t[0] != '{' {
		return errors.New("not a JSON object")
	}
	return json.Unmarshal(b, v)
}

func ParseConfigCheck(b []byte) (ConfigCheckOutput, error) {
	var o ConfigCheckOutput
	err := parseObject(b, &o)
	return o, err
}

// ParseConfigReload reads a successful reload: generation and diagnostics
// are both required, diagnostics may be null.
func ParseConfigReload(b []byte) (ConfigReloadOutput, error) {
	var o ConfigReloadOutput
	var keys map[string]json.RawMessage
	if err := parseObject(b, &keys); err != nil {
		return o, err
	}
	if err := json.Unmarshal(b, &o); err != nil {
		return o, err
	}
	switch g := bytes.TrimSpace(keys["generation"]); {
	case len(g) == 0 || string(g) == "null":
		return o, errors.New("no generation in the output")
	case keys["diagnostics"] == nil:
		return o, errors.New("no diagnostics in the output")
	}
	return o, nil
}

// ParseConfigDiagnostics reads the diagnostics of any config command's
// output, a failed one included.
func ParseConfigDiagnostics(b []byte) ([]ConfigDiagnostic, error) {
	var o struct {
		Diagnostics []ConfigDiagnostic `json:"diagnostics"`
	}
	err := parseObject(b, &o)
	return o.Diagnostics, err
}

// FirstComplaint is the first error diagnostic, else the first one.
func FirstComplaint(ds []ConfigDiagnostic) (ConfigDiagnostic, bool) {
	if i := slices.IndexFunc(ds, func(d ConfigDiagnostic) bool { return d.Severity == "error" }); i >= 0 {
		return ds[i], true
	}
	if len(ds) > 0 {
		return ds[0], true
	}
	return ConfigDiagnostic{}, false
}

// CheckHostsFile has this machine's rex check data as a config file, through
// a private copy in runtimeDir that never outlives the check. Only a report
// for that very copy, with no diagnostic at all, passes.
func CheckHostsFile(ctx context.Context, home *Client, runtimeDir string, pid int, data []byte) error {
	p := runtimeDir + "/hosts-check-" + strconv.Itoa(pid) + ".lua"
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	// O_EXCL also refuses a symlink planted at p since the removal.
	f, err := os.OpenFile(p, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	defer os.Remove(p)
	_, werr := f.Write(data)
	if cerr := f.Close(); werr == nil {
		werr = cerr
	}
	if werr != nil {
		return werr
	}
	out, err := home.Exec(ctx, Commands{}.ConfigCheck(p), false)
	if err != nil {
		return err
	}
	o, perr := ParseConfigCheck(out.Stdout)
	var complaint ConfigDiagnostic
	found := false
	if perr == nil && o.Diagnostics != nil {
		complaint, found = FirstComplaint(*o.Diagnostics)
	}
	switch {
	case found:
		return errors.New(complaint.Text())
	case out.Kind != ExitOK:
		return errors.New(out.Toast)
	case perr != nil:
		return fmt.Errorf("unreadable output: %v", perr)
	case o.Exists == nil || !*o.Exists:
		return errors.New("rex did not find the file")
	case o.Path != p:
		return fmt.Errorf("rex checked %s, not %s", o.Path, p)
	case o.Diagnostics == nil:
		return errors.New("no diagnostics in the output")
	}
	return nil
}

// IsDeclared reports whether a config file declares h: the server sets
// Source to FILE.lua:LINE then, and leaves it out for a stored host.
func IsDeclared(h Host) bool { return declaredRE.MatchString(string(h.Source)) }

// IsManaged reports whether lazyrex's own file declares h.
func IsManaged(h Host) bool {
	if !IsDeclared(h) {
		return false
	}
	src := string(h.Source)
	return path.Base(src[:strings.LastIndexByte(src, ':')]) == HostsFileName
}

// IsOwnHost reports whether h has the shape of a host lazyrex declares:
// declared, a -lazyrex label, and only stable gui sockets as endpoints.
func IsOwnHost(h Host) bool {
	if !IsDeclared(h) || !hostLabelRE.MatchString(h.Label) || len(h.Endpoints) == 0 {
		return false
	}
	for _, ep := range h.Endpoints {
		p, err := NormalizeEndpoint(string(ep))
		if err != nil || !stableSockRE.MatchString(path.Base(p)) {
			return false
		}
	}
	return true
}
